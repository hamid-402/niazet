import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { buildZ1Contracts } from './zeus-z1-contract-inventory.mjs';
const root = new URL('../../', import.meta.url);
const read = path => readFileSync(new URL(path, root), 'utf8').replaceAll('\r\n', '\n');
const json = path => JSON.parse(read(path));
const evidence = json('docs/zeus/z1-phase-acceptance.json');
assert.equal(evidence.phase, 'Z1'); assert.equal(evidence.packet, 'ZEUS-EXEC-010');
assert.equal(evidence.baseline, '2c701d7'); assert.equal(evidence.acceptedCommit, null);
assert.equal(evidence.sourceAccepted, true); assert.equal(evidence.readyForLocalActivation, true);
assert.equal(evidence.productAccepted, false); assert.equal(evidence.literalD1TechnologyAccepted, false);
assert.deepEqual(evidence.localSubtasksAccepted, ['Z1.1', 'Z1.2', 'Z1.3', 'Z1.4', 'Z1.5', 'Z1.6']);
for (const [path, expected] of Object.entries(evidence.fileHashes)) assert.equal(createHash('sha256').update(read(path)).digest('hex'), expected, 'Z1 final certificate input drift: ' + path);
const contracts = buildZ1Contracts();
assert.equal(contracts.api.length, 84); assert.equal(contracts.data.length, 120);
assert.deepEqual(json('.artifacts/zeus/z1-phase/contract-inventory.json'), contracts);
const http = evidence.acceptance.http;
assert.equal(http.status, 'passed'); assert.equal(http.contractRows.length, 84); assert.equal(http.deployedTargets, 76);
assert.equal(http.openApiTargetsVerified, 76); assert.equal(http.mainDatabaseConnected, false);
assert.equal(http.temporaryDatabaseRemoved, true); assert.equal(http.cases.length, 8);
assert.deepEqual(http.contractRows.map(r => r.id), contracts.api.map(r => r.id));
assert.equal(evidence.acceptance.api.suitesPassed, 45); assert.equal(evidence.acceptance.api.testsPassed, 339);
assert.equal(evidence.acceptance.api.preExistingSkipped, 1);
assert.equal(evidence.acceptance.orderBranches.passed, 9); assert.equal(evidence.acceptance.orderBranches.rejectedMutations, 45);
assert.equal(evidence.acceptance.walletAndAuth.groupsPassed, 26);
assert.equal(evidence.acceptance.approvalTests, 53); assert.equal(evidence.acceptance.web.structuralContractsPassed, 24);
assert.equal(evidence.acceptance.web.registrationBrowser.results.length, 4);
const upgrade = evidence.acceptance.upgrade;
assert.equal(upgrade.status, 'passed'); assert.equal(upgrade.previousTablesPreserved, 70);
assert.equal(upgrade.previousClientReadWriteAfterUpgrade, true); assert.equal(upgrade.generatedFixtureRemoved, true);
assert.equal(upgrade.temporaryDatabaseRemoved, true); assert.equal(upgrade.mainDatabaseConnected, false);
assert.equal(upgrade.targetMigrationHash, evidence.fileHashes['apps/api/prisma/migrations/20261026100000_zeus_data_contracts/migration.sql']);
assert.equal(upgrade.schemaHash, evidence.fileHashes['apps/api/prisma/schema.prisma']);
const earlier = json('docs/zeus/z1-foundation-acceptance.json');
for (const path of ['apps/api/package.json', 'apps/api/package-lock.json', 'apps/web/package.json', 'apps/web/package-lock.json']) assert.equal(evidence.fileHashes[path], earlier.fileHashes[path], 'Earlier audit cannot certify changed dependencies');
assert.equal(evidence.scope.newRegistryAudit, false); assert.equal(evidence.scope.liveProviders, false);
assert.equal(evidence.scope.accountMerge, false); assert.equal(evidence.scope.mainFinancialAcceptanceWrites, false);
assert.equal(evidence.scope.aiEngineAccepted, false); assert.equal(evidence.scope.baseline192Rewritten, false);
if (!process.argv.includes('--pre-activation')) {
  assert.equal(evidence.phaseAccepted, true);
  assert.equal(evidence.localActivation.status, 'passed'); assert.equal(evidence.localActivation.migrationCount, 25);
  assert.equal(evidence.localActivation.previousTablesPreserved, 70);
  assert.equal(evidence.localActivation.mainFinancialAcceptanceWrites, false);
  assert.equal(evidence.runtime.api, 'healthy'); assert.equal(evidence.runtime.web, 'healthy');
  assert.equal(evidence.runtime.allWalletsConsistent, true);
}
