import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
const root = new URL('../../', import.meta.url);
const read = path => readFileSync(new URL(path, root), 'utf8').replaceAll('\r\n', '\n');
const hash = value => createHash('sha256').update(value).digest('hex');
const evidence = JSON.parse(read('docs/zeus/z1-local-activation.json'));
assert.equal(evidence.packet, 'ZEUS-EXEC-008');
assert.equal(evidence.baseline, '2c701d7');
assert.equal(evidence.phaseAccepted, false);
assert.equal(evidence.productAccepted, false);
assert.equal(evidence.acceptedCommit, null);
assert.deepEqual(evidence.localSubtasksAccepted, ['Z1.4', 'Z1.5', 'Z1.6']);
assert.equal(evidence.permission.mainDatabaseMigration, true);
for (const field of ['mainLedgerMutationDuringAcceptance', 'liveProviders', 'accountMerge']) assert.equal(evidence.permission[field], false);
assert.equal(evidence.activation.paymentGatewayDriver, 'mock');
assert.equal(evidence.activation.walletSwitchEnabled, true);
assert.equal(evidence.activation.productionMockFundingForbidden, true);
assert.equal(evidence.activation.migrationCount, 24);
assert.equal(evidence.mainMigration.existingDataUnchanged, true);
assert.equal(evidence.mainMigration.existingTables, 64);
assert.equal(evidence.mainMigration.seedExecuted, false);
assert.equal(evidence.rehearsal.actualOldGeneratedClientReadWrite, true);
assert.equal(evidence.rehearsal.oldClientReadsNewFinancialEntries, true);
assert.equal(evidence.rehearsal.temporaryDatabaseAndClientRemoved, true);
for (const [path, expected] of Object.entries(evidence.fileHashes)) assert.equal(hash(read(path)), expected, 'Activation evidence drift: ' + path);
const historical = JSON.parse(read('docs/zeus/z1-foundation-acceptance.json'));
for (const path of evidence.security.unchangedDependencyInputs) assert.equal(hash(read(path)), historical.fileHashes[path], 'Previous audit no longer applies: ' + path);
assert.equal(evidence.security.auditRerunInActivationPacket, false);
assert.equal(evidence.browser.uiFixturesOnly, true);
assert.equal(evidence.browser.mainDatabaseTouched, false);
assert.equal(evidence.browser.results.length, 4);
assert(evidence.browser.results.every(r => r.status === 'passed' && r.axeViolations === 0));
console.log('ZEUS-EXEC-008 activation evidence matches exact current source/test/guard inputs. Local mock wallet enabled; existing data preserved. NOT whole-phase/product/CI/live acceptance.');
